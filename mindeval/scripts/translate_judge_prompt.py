"""
Translate Mind-Eval judge prompt to other languages for Option B evaluation.

This script translates the English judge prompt to Chinese, Korean, or other
languages while preserving the evaluation framework and criteria structure.

Usage:
    # Method 1: Using config file (recommended)
    python mindeval/scripts/translate_judge_prompt.py \
        --target_language zh \
        --output_path mindeval/judge_prompts_zh.py \
        --config_path config.json
    
    # Method 2: Using direct API parameters
    python mindeval/scripts/translate_judge_prompt.py \
        --target_language zh \
        --output_path mindeval/judge_prompts_zh.py \
        --model_api_params "{'model':'gpt-4','api_key':'YOUR_KEY'}"
    
    # Translate to Korean
    python mindeval/scripts/translate_judge_prompt.py \
        --target_language ko \
        --output_path mindeval/judge_prompts_ko.py \
        --config_path config.json
"""

import json
from pathlib import Path
from typing import Dict, Any, Optional
from string import Template

from mindeval.inference import InferenceEngine
from mindeval.judge_prompts import JUDGE_PROMPT_TEMPLATE


LANGUAGE_NAMES = {
    "zh": "Chinese (Simplified)",
    "zh-TW": "Chinese (Traditional)",
    "ko": "Korean",
    "ja": "Japanese",
    "vi": "Vietnamese",
    "th": "Thai"
}


def translate_judge_prompt(
    target_language: str,
    model_api_params: Dict[str, Any],
    preserve_structure: bool = True
) -> str:
    """
    Translate judge prompt to target language.
    
    Args:
        target_language: Target language code (zh, ko, ja, etc.)
        model_api_params: API parameters for translation model
        preserve_structure: Whether to preserve XML tags and structure
        
    Returns:
        Translated prompt template string
    """
    language_name = LANGUAGE_NAMES.get(target_language, target_language)
    
    # Get the template string
    template_str = JUDGE_PROMPT_TEMPLATE.template
    
    # Create translation prompt
    translation_prompt = f"""You are translating a mental health evaluation rubric from English to {language_name}.

CRITICAL REQUIREMENTS:
1. Preserve ALL XML tags exactly as they are (e.g., <evaluation_framework>, <criterion_1>, etc.)
2. Preserve ALL Template variables exactly as they are (e.g., $conversation_str, $name, etc.)
3. Translate the content while maintaining:
   - Professional clinical terminology
   - Evaluation framework structure
   - Rating scale meanings
   - Criterion definitions and examples
4. Ensure cultural appropriateness for {language_name} mental health context
5. Maintain the same level of detail and nuance

IMPORTANT: This is a professional clinical evaluation tool. Translation must be:
- Accurate and precise
- Culturally sensitive
- Clinically appropriate
- Maintaining the same evaluation standards

Original English prompt:
{template_str}

Translated {language_name} prompt:"""
    
    # Call translation model
    model = InferenceEngine(model_api_params)
    messages = [{"role": "user", "content": translation_prompt}]
    
    print(f"Translating judge prompt to {language_name}...")
    print("This may take 2-3 minutes due to the length of the prompt...")
    
    translated = model.generate(messages)
    
    return translated.strip()


def validate_translation(
    original: str,
    translated: str,
    target_language: str
) -> Dict[str, Any]:
    """
    Validate that translation preserves structure.
    
    Returns:
        Dict with validation results
    """
    import re
    
    # Check XML tags
    original_tags = set(re.findall(r'<[^>]+>', original))
    translated_tags = set(re.findall(r'<[^>]+>', translated))
    
    # Check Template variables
    original_vars = set(re.findall(r'\$\w+', original))
    translated_vars = set(re.findall(r'\$\w+', translated))
    
    missing_tags = original_tags - translated_tags
    missing_vars = original_vars - translated_vars
    
    validation = {
        "valid": len(missing_tags) == 0 and len(missing_vars) == 0,
        "missing_tags": list(missing_tags),
        "missing_vars": list(missing_vars),
        "original_length": len(original),
        "translated_length": len(translated)
    }
    
    return validation


def save_translated_prompt(
    translated_prompt: str,
    output_path: str,
    target_language: str
):
    """
    Save translated prompt as Python module.
    """
    language_name = LANGUAGE_NAMES.get(target_language, target_language)
    
    module_content = f'''"""
Mind-Eval Judge Prompt - {language_name} Translation

This is a translated version of the Mind-Eval judge prompt for evaluating
mental health conversations in {language_name}.

Generated by: translate_judge_prompt.py
Target language: {target_language}
"""

from string import Template

JUDGE_PROMPT_TEMPLATE_{target_language.upper().replace("-", "_")} = Template(
"""{translated_prompt}"""
)

# Alias for convenience
JUDGE_PROMPT_TEMPLATE = JUDGE_PROMPT_TEMPLATE_{target_language.upper().replace("-", "_")}
'''
    
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(module_content)
    
    print(f"\n✓ Translated prompt saved to: {output_path}")


def main(
    target_language: str,
    output_path: str,
    model_api_params: Optional[Dict[str, Any]] = None,
    config_path: Optional[str] = None,
    validate: bool = True
):
    """
    Main function to translate judge prompt.
    
    Args:
        target_language: Target language code (zh, ko, ja, etc.)
        output_path: Output path for translated prompt module
        model_api_params: API parameters for translation model (optional)
        config_path: Path to config file (optional, used if model_api_params is None)
        validate: Whether to validate translation structure
    """
    if target_language not in LANGUAGE_NAMES:
        print(f"Warning: Language '{target_language}' not in predefined list.")
        print(f"Supported languages: {', '.join(LANGUAGE_NAMES.keys())}")
        response = input("Continue anyway? (y/n): ")
        if response.lower() != 'y':
            return
    
    # Get translation config
    if model_api_params is None:
        from mindeval.config import get_translation_config
        model_api_params = get_translation_config(config_path)
    
    # Translate
    translated = translate_judge_prompt(
        target_language=target_language,
        model_api_params=model_api_params
    )
    
    # Validate
    if validate:
        print("\nValidating translation...")
        original = JUDGE_PROMPT_TEMPLATE.template
        validation = validate_translation(original, translated, target_language)
        
        if validation["valid"]:
            print("✓ Translation validation passed!")
        else:
            print("⚠ Translation validation issues:")
            if validation["missing_tags"]:
                print(f"  Missing XML tags: {validation['missing_tags']}")
            if validation["missing_vars"]:
                print(f"  Missing variables: {validation['missing_vars']}")
            
            response = input("\nContinue saving despite validation issues? (y/n): ")
            if response.lower() != 'y':
                return
    
    # Save
    save_translated_prompt(translated, output_path, target_language)
    
    # Print summary
    print("\n" + "="*80)
    print("  TRANSLATION COMPLETE")
    print("="*80)
    print(f"Language: {LANGUAGE_NAMES.get(target_language, target_language)}")
    print(f"Output: {output_path}")
    print(f"Original length: {len(JUDGE_PROMPT_TEMPLATE.template)} chars")
    print(f"Translated length: {len(translated)} chars")
    print("\nNext steps:")
    print("1. Review the translated prompt for accuracy")
    print("2. Have a native speaker validate clinical terminology")
    print("3. Use with generate_judgments.py --judge_template_path")


if __name__ == "__main__":
    from jsonargparse import CLI
    CLI([main], as_positional=False)
